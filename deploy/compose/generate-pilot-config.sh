#!/bin/sh
# Generates the configuration of an operated pilot (#96) under PILOT_HOME:
# a private CA, one server certificate for every TLS listener of the stack,
# database, S3, Keycloak and attach-key secrets, the identity configuration and
# the env file Compose reads. It never overwrites a secret, key or certificate
# that already exists, so it is safe to run again. deploy/compose/PILOT.md is
# the runbook.
#
# usage: generate-pilot-config.sh PILOT_HOME RELEASE_MANIFEST [EXTRA_HOST_NAME...]
#
# Extra host names are added to the server certificate, for example the
# pilot's Tailscale name, so callers outside the Compose network can verify it.
set -eu

if [ "$#" -lt 2 ]; then
  echo "usage: $0 PILOT_HOME RELEASE_MANIFEST [EXTRA_HOST_NAME...]" >&2
  exit 2
fi
home=$1
manifest=$2
shift 2
command -v jq >/dev/null || { echo "jq is required" >&2; exit 2; }
command -v openssl >/dev/null || { echo "openssl is required" >&2; exit 2; }
[ -s "$manifest" ] || { echo "release manifest $manifest is missing" >&2; exit 2; }

config="$home/config"
secrets="$home/secrets"
umask 077
mkdir -p "$config" "$secrets"
chmod 0700 "$home" "$config" "$secrets"

image() {
  value=$(jq -er --arg name "$1" '.images[$name]' "$manifest")
  case "$value" in
    *@sha256:*) printf '%s' "$value" ;;
    *) echo "image $1 in $manifest is not named by digest" >&2; exit 1 ;;
  esac
}

write_secret() {
  if [ ! -s "$1" ]; then
    openssl rand -hex 24 >"$1"
  fi
}

for name in postgres-migrate-password postgres-serve-password s3-operator-secret s3-adapter-secret \
  keycloak-db-password keycloak-admin-password; do
  write_secret "$secrets/$name"
done
# The key both adapters derive exec-server tokens from, sized as qualify-providers sizes it.
if [ ! -s "$secrets/environment-attach-key" ]; then
  openssl rand -hex 32 >"$secrets/environment-attach-key"
fi

if [ ! -s "$config/ca.crt" ] || [ ! -s "$secrets/ca.key" ]; then
  openssl req -x509 -newkey rsa:3072 -nodes -days 365 \
    -subj "/CN=dac-plane pilot CA" \
    -keyout "$secrets/ca.key" -out "$config/ca.crt"
fi

# One certificate serves the control plane, the artifact store and Keycloak,
# under their Compose service names and any extra names given.
sans="DNS:dac-plane,DNS:artifact-store,DNS:keycloak,DNS:localhost,IP:127.0.0.1"
for name in "$@"; do
  sans="$sans,DNS:$name"
done
if [ ! -s "$config/server.crt" ] || [ ! -s "$secrets/server.key" ]; then
  openssl req -new -newkey rsa:2048 -nodes -subj "/CN=dac-plane" \
    -addext "subjectAltName=$sans" \
    -keyout "$secrets/server.key" -out "$secrets/server.csr"
  openssl x509 -req -days 90 -in "$secrets/server.csr" \
    -CA "$config/ca.crt" -CAkey "$secrets/ca.key" -CAcreateserial \
    -copy_extensions copy -out "$config/server.crt"
  rm -f "$secrets/server.csr"
fi

migrate_password=$(cat "$secrets/postgres-migrate-password")
serve_password=$(cat "$secrets/postgres-serve-password")
for name in migrate-database-url serve-database-url s3-identities.json; do
  if [ -e "$secrets/$name" ]; then chmod 0600 "$secrets/$name"; fi
done
printf 'postgres://dac_migrate:%s@postgres:5432/dac?sslmode=disable\n' "$migrate_password" >"$secrets/migrate-database-url"
printf 'postgres://dac_serve:%s@postgres:5432/dac?sslmode=disable\n' "$serve_password" >"$secrets/serve-database-url"

# The adapter identity is never an S3 admin, because SeaweedFS admins bypass
# governance retention.
printf '{"identities":[{"name":"operator","credentials":[{"accessKey":"dac-operator","secretKey":"%s"}],"actions":["Admin","Read","Write","List","Tagging"]},{"name":"adapter","credentials":[{"accessKey":"dac-adapter","secretKey":"%s"}],"actions":["Read:dac-staging","Write:dac-staging","List:dac-staging","Read:dac-objects","Write:dac-objects","List:dac-objects"]}]}\n' \
  "$(cat "$secrets/s3-operator-secret")" "$(cat "$secrets/s3-adapter-secret")" >"$secrets/s3-identities.json"

# Keycloak's access tokens carry typ "Bearer" and a JWT header typ of "JWT",
# not at+jwt, so the type check is off. Each audience is issued only by this
# realm's audience scopes, which is the condition authn.IssuerConfig sets.
cat >"$config/identity.json" <<'EOF'
{
  "issuers": [
    {
      "issuer": "https://keycloak:8443/realms/dac",
      "audience": "dac-plane-surface",
      "algorithms": ["RS256"],
      "max_token_lifetime_seconds": 600,
      "require_access_token_type": false
    }
  ],
  "adapter_issuers": [
    {
      "issuer": "https://keycloak:8443/realms/dac",
      "audience": "dac-plane-adapters",
      "algorithms": ["RS256"],
      "max_token_lifetime_seconds": 600,
      "require_access_token_type": false
    }
  ]
}
EOF

# Client secrets and provider identifiers are written by configure-pilot.sh.
# Provider credentials are placed by the operator.
if [ ! -e "$home/pilot.env" ]; then
  cat >"$home/pilot.env" <<EOF
# Generated by generate-pilot-config.sh. Paths are host paths. Edit the
# provider settings below; configure-pilot.sh appends identifiers.
DAC_PLANE_IMAGE=$(image dac-plane)
DAC_CODEX_ADAPTER_IMAGE=$(image dac-codex-adapter)
DAC_E2B_ADAPTER_IMAGE=$(image dac-e2b-adapter)
DAC_S3_ADAPTER_IMAGE=$(image dac-s3-adapter)
DAC_SURFACE_BIND=127.0.0.1
DAC_SURFACE_PORT=8443
DAC_ISSUER_BIND=127.0.0.1
DAC_ISSUER_PORT=18443
DAC_IDENTITY_CONFIG_FILE=$config/identity.json
DAC_TLS_CERT_FILE=$config/server.crt
DAC_TLS_KEY_FILE=$secrets/server.key
DAC_TRUST_BUNDLE_FILE=$config/ca.crt
DAC_POSTGRES_MIGRATE_PASSWORD_FILE=$secrets/postgres-migrate-password
DAC_POSTGRES_SERVE_PASSWORD_FILE=$secrets/postgres-serve-password
DAC_MIGRATE_DATABASE_URL_FILE=$secrets/migrate-database-url
DAC_SERVE_DATABASE_URL_FILE=$secrets/serve-database-url
DAC_KEYCLOAK_DB_PASSWORD_FILE=$secrets/keycloak-db-password
DAC_KEYCLOAK_ADMIN_PASSWORD_FILE=$secrets/keycloak-admin-password
DAC_ADAPTER_TOKEN_URL=https://keycloak:8443/realms/dac/protocol/openid-connect/token
DAC_RUNTIME_CLIENT_ID=dac-runtime-adapter
DAC_ENVIRONMENT_CLIENT_ID=dac-environment-adapter
DAC_ARTIFACT_CLIENT_ID=dac-artifact-adapter
DAC_RUNTIME_CLIENT_SECRET_FILE=$secrets/runtime-client-secret
DAC_ENVIRONMENT_CLIENT_SECRET_FILE=$secrets/environment-client-secret
DAC_ARTIFACT_CLIENT_SECRET_FILE=$secrets/artifact-client-secret
DAC_ENVIRONMENT_ATTACH_KEY_FILE=$secrets/environment-attach-key
DAC_S3_IDENTITIES_FILE=$secrets/s3-identities.json
DAC_S3_OPERATOR_SECRET_FILE=$secrets/s3-operator-secret
DAC_S3_ADAPTER_SECRET_FILE=$secrets/s3-adapter-secret
DAC_CODEX_API_KEY_FILE=$secrets/model-api-key
DAC_E2B_API_KEY_FILE=$secrets/e2b-api-key
# Provider settings: set these before deploying.
DAC_CODEX_MODEL_PROVIDER=
DAC_CODEX_MODEL=
DAC_CODEX_BASE_URL=
DAC_E2B_TEMPLATE_ID=
EOF
fi

# Local Compose bind-mounts file-backed configs and secrets, so container users
# need read permission on the files; the directories stay owner-only and every
# mount is read-only.
chmod 0444 "$config/ca.crt" "$config/server.crt" "$config/identity.json" "$secrets/server.key" \
  "$secrets/postgres-migrate-password" "$secrets/postgres-serve-password" \
  "$secrets/migrate-database-url" "$secrets/serve-database-url" \
  "$secrets/s3-operator-secret" "$secrets/s3-adapter-secret" "$secrets/s3-identities.json" \
  "$secrets/keycloak-db-password" "$secrets/keycloak-admin-password" "$secrets/environment-attach-key"
chmod 0400 "$secrets/ca.key"
chmod 0600 "$home/pilot.env"
echo "pilot configuration written under $home"
