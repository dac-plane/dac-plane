#!/usr/bin/env bash
# Prints the license and notice files of every module linked into a published
# binary, on either published architecture. Fails if a module has neither, so a
# new dependency cannot ship without its notices. Versions are left out, so a
# version bump changes this output only when the license text itself changes.
# Modules on two versions print the newest one's files.
set -euo pipefail
export LC_ALL=C GOOS=linux CGO_ENABLED=0 GOFLAGS=-mod=readonly

format='{{with .Module}}{{.Path}} {{.Version}} {{.Dir}}{{end}}'
modules() {
	for target in .:./cmd/dac-plane adapters/codex:./cmd/dac-codex-adapter adapters/e2b:./cmd/dac-e2b-adapter adapters/s3:./cmd/dac-s3-adapter; do
		for arch in amd64 arm64; do
			(cd "${target%%:*}" && GOARCH="$arch" go list -deps -f "$format" "${target##*:}")
		done
	done | grep -v '^github.com/dac-plane/dac-plane' | sort -k1,1 -k2,2Vr | sort -s -u -k1,1
}

printf 'Third-party notices for the Go code in the published dac-plane images.\n'
printf 'Generated by scripts/release/generate-notices.sh. Do not edit.\n\n'
printf '=== Go standard library\n\n'
cat "$(go env GOROOT)/LICENSE"

modules | while read -r module _ dir; do
	files=$(find "$dir" -maxdepth 1 -type f \( -iname 'LICEN[CS]E*' -o -iname 'COPYING*' -o -iname 'NOTICE*' \) | sort)
	if [ -z "$files" ]; then
		echo "no license file for $module" >&2
		exit 1
	fi
	printf '\n=== %s\n' "$module"
	for file in $files; do
		printf '\n'
		cat "$file"
	done
done
